#!/bin/sh
# Regenerates stack.yml. Run after every upstream merge: docker-compose.yml's env forwards change.
# --no-interpolate and the empty env file keep .env values out of the output.
set -eu
cd "$(dirname "$0")/../.."
{
  echo '# GENERATED by ops/portainer/generate-stack.sh. Do not edit; see ops/portainer/README.md.'
  docker compose --env-file /dev/null -p openwa-prod \
    -f docker-compose.yml -f docker-compose.override.yml -f ops/portainer/stack.override.yml \
    config --no-interpolate
} > ops/portainer/stack.yml.tmp
mv ops/portainer/stack.yml.tmp ops/portainer/stack.yml
